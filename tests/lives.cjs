const { launch, click, sleep, errors } = require("./harness.cjs");
const assert = require("node:assert/strict");
const stamp = 1_800_000_000_000, halfHour = 30 * 60_000, saveKey = "catnap.save.v1";
const saved = (w) => JSON.parse(w.localStorage.getItem(saveKey));
const count = (w) => w.document.querySelector(".lives-meter strong").textContent;
const cat = (w, cell) => w.document.querySelectorAll(".cell")[cell].dispatchEvent(new w.KeyboardEvent("keydown", { key: "c", bubbles: true }));
async function pair(w, cell) {
  const button = w.document.querySelectorAll(".cell")[cell];
  button.dispatchEvent(new w.MouseEvent("click", { bubbles: true, detail: 1 }));
  button.dispatchEvent(new w.MouseEvent("click", { bubbles: true, detail: 2 }));
  await sleep(30);
}
(async () => {
  let dom = await launch({}, true, { now: stamp }), w = dom.window;
  const oldBackup = JSON.stringify(saved(w));
  assert.equal(count(w), "3 / 3");
  w.document.querySelectorAll(".cell")[0].click(); await sleep(20);
  w.document.querySelectorAll(".cell")[0].click(); await sleep(20);
  assert.equal(count(w), "3 / 3", "Adding and erasing X notes do not cost lives");
  cat(w, 4); await sleep(30);
  assert.equal(count(w), "3 / 3", "Correct placements keep all lives");
  cat(w, 0); await sleep(30);
  assert.equal(count(w), "2 / 3");
  assert.equal(w.document.querySelectorAll(".cell.has-cat").length, 1, "Wrong cats are rejected");
  assert.equal(w.document.querySelector(".life-next-timer").textContent, "30:00");
  await click(w, "Undo");
  assert.equal(count(w), "2 / 3", "Undo does not refund a life");
  w.__setNow(stamp + 10 * 60_000);
  await pair(w, 0);
  assert.equal(count(w), "1 / 3");
  const current = Object.values(saved(w).games).find((g) => g.levelId === "level-001");
  assert.deepEqual(current.marks, [], "Rejected double taps restore the state before the first tap");
  assert.equal(w.document.querySelector(".life-next-timer").textContent, "20:00");
  await pair(w, 0);
  assert.equal(count(w), "0 / 3");
  assert.ok(w.document.querySelector(".life-cover"));
  assert.ok([...w.document.querySelectorAll(".cell")].every((b) => b.disabled));
  const receipts = saved(w).lives;
  cat(w, 4); await sleep(20);
  assert.deepEqual(saved(w).lives, receipts, "Blocked input cannot spend another life");
  await click(w, "Daily puzzle");
  assert.equal(count(w), "0 / 3", "Changing puzzles preserves the recharge schedule");
  await click(w, "Restart"); await click(w, "Restart this puzzle");
  assert.equal(count(w), "0 / 3", "Restart cannot reset lives");
  w.document.querySelector('[aria-label="Settings and backups"]').click(); await sleep(30);
  const input = w.document.querySelector("input[type=file]");
  Object.defineProperty(input, "files", { value: [new w.File([oldBackup], "old.json", { type: "application/json" })] });
  input.dispatchEvent(new w.Event("change", { bubbles: true })); await sleep(120);
  assert.equal(count(w), "0 / 3", "Importing an older full-life backup does not refill lives");
  const snapshot = {};
  for (let i = 0; i < w.localStorage.length; i++) { const key = w.localStorage.key(i); snapshot[key] = w.localStorage.getItem(key); }
  dom.window.close();
  dom = await launch(snapshot, true, { now: stamp + 20 * 60_000 }); w = dom.window;
  assert.equal(count(w), "0 / 3", "Missing lives survive closing and reopening");
  assert.equal(w.document.querySelector(".life-next-timer").textContent, "10:00");
  w.__setNow(stamp + halfHour); w.dispatchEvent(new w.Event("focus")); await sleep(40);
  assert.equal(count(w), "1 / 3", "The first life returns at 30 minutes without a reload");
  assert.equal(w.document.querySelector(".life-cover") === null, true);
  assert.ok([...w.document.querySelectorAll(".cell")].every((b) => !b.disabled));
  w.__setNow(stamp + 3 * halfHour); w.document.dispatchEvent(new w.Event("visibilitychange")); await sleep(30);
  assert.equal(count(w), "3 / 3", "All three return after 90 minutes away from the tab");
  assert.equal(w.document.querySelector(".life-next-timer") === null, true);
  assert.deepEqual(errors, []);
  dom.window.close();
  console.log("Lives integration passed: wrong/correct cats, double-tap rollback, zero-life lock, serial recharge, undo/restart/navigation, old imports, reload and offline recovery.");
})().catch((error) => { console.error(error); process.exitCode = 1; setTimeout(() => process.exit(1), 100); });
