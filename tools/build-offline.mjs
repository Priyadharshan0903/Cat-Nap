import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../dist/", import.meta.url));
const manifest = JSON.parse(
  readFileSync(join(root, ".vite/manifest.json"), "utf8"),
);
const files = [
  ...new Set([
    "index.html",
    "manifest.webmanifest",
    "favicon.svg",
    "apple-touch-icon.png",
    "icon-192.png",
    "icon-512.png",
    ...Object.values(manifest).flatMap((entry) => [
      entry.file,
      ...(entry.css || []),
      ...(entry.assets || []),
    ]),
  ]),
];
const paths = files.map((file) => join(root, file));
const hash = createHash("sha256");
for (const path of paths) hash.update(readFileSync(path));
const version = hash.digest("hex").slice(0, 12);
const source = `// Generated by tools/build-offline.mjs. All URLs are relative to the GitHub Pages project path.
const PREFIX = 'catnap-' + encodeURIComponent(new URL(self.registration.scope).pathname) + '-';
const CACHE = PREFIX + '${version}';
const FILES = ${JSON.stringify(files)};
const scope = new URL(self.registration.scope);
const home = () => new URL('index.html', scope).href;
self.addEventListener('install', event => event.waitUntil((async () => { const cache = await caches.open(CACHE); await cache.addAll(FILES.map(file => new URL(file, scope).href)); })()));
// A new release waits for open game tabs to close, so a move is never interrupted by an update.
self.addEventListener('activate', event => event.waitUntil((async () => { for (const key of await caches.keys()) if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key); await self.clients.claim(); })()));
self.addEventListener('message', event => { if (event.data?.type === 'CACHE_HOME') event.waitUntil((async () => { const response = await fetch(home()); if (response.ok && !response.redirected) await (await caches.open(CACHE)).put(home(), response); })()); });
self.addEventListener('fetch', event => {
  const request = event.request, url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Serve the matching, fully cached release for both HTML and assets. A waiting worker activates on the next visit.
    if (request.mode === 'navigate') return (await cache.match(home())) || fetch(request);
    return (await cache.match(request)) || fetch(request);
  })());
});
`;
writeFileSync(join(root, "sw.js"), source);
writeFileSync(join(root, ".nojekyll"), "");
console.log(`Offline cache: ${files.length} files; release ${version}`);
